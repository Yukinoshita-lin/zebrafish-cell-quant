# ---------------------------------------------------------------- 公共片段
IMG_INFO = """【图像基本信息】
  尺寸 2752 x 2208 像素，uint8，3 通道（BGR），单张约 7 MB。
  荧光信号在 G 通道（lyz:EGFP 绿色荧光），R 通道最弱。
  目标细胞（中性粒细胞）为直径约 5~10 px 的绿色荧光斑点，
  每张图约 100~400 个（造模炎症图密度最高）。"""

BOX_RULES = """【标注规范 —— 检测框（YOLO 格式）】
  1. 所有明显的绿色荧光亮点都要画框，肠内、肠外都画
     （肠外部分后续由中后肠掩码过滤，检测器需要见过这些信号）。
  2. 框紧贴细胞外沿，尽量方正，不要过大或过小。
  3. 粘连/成串的细胞必须分开画，一个框只包一个细胞
     （这一步对计数准确性至关重要）。
  4. 极弱、无法确认是细胞的信号不画（宁缺毋滥）；
     但明显成串或成簇的都要逐一画出。
  5. 明场残留的团块、杂质、死细胞的碎亮不画。"""

BOX_TOOL = """【工具与输出】
  推荐 LabelImg（YOLO 格式）或 CVAT。
  类别只有 1 个：cell（class id = 0）。
  每张图标注完成后，保存为与图像同名的 .txt（仅扩展名不同），
  放到本文件夹下的 labels/ 子目录中。
  YOLO 格式每行：0 cx cy w h（cx,cy 为框中心，w,h 为框宽高，
  全部用 0~1 归一化值，相对原图 2752x2208）。"""

QC = """【质控要求】
  每完成 10 张自查一次：抽查 2 张与原始图像核对。
  漏标率/错标率超过 10% 的批次整批返工。
  拿不准的细胞：先标上，并在 labels/ 同级的 疑问记录.txt 里
  记下文件名，统一复核。"""

DRAFT_NOTE = """【草稿标注说明】
  经典荧光算法（top-hat + Otsu + 连通域）可为每张图生成草稿框，
  届时会随包提供或另行通知。有草稿时：人工只做"删错、补漏、拆分粘连"，
  单张约 1~2 分钟；没有草稿时从头画，单张约 10~20 分钟。
  格式可参考项目 dataset/labels/ 目录下的 230 个草稿样例
  （均为对照组切块标注，YOLO 格式）。"""


def _checklist(names: List[str], cols: int = 4) -> str:
    lines = []
    for i in range(0, len(names), cols):
        row = names[i:i + cols]
        lines.append("  " + "  ".join(f"☐ {n}" for n in row))
    return "\n".join(lines)


