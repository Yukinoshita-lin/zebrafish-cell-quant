def note_mask(names: List[str]) -> str:
    return f"""斑马鱼肠道炎症细胞定量 —— 待标注工作说明
{'=' * 56}
文件夹：05_中后肠掩码_60张
任务：中后肠区域分割标注（多边形轮廓）
张数：{len(names)} 张

【本文件夹用途】
  需求 4.2/4.3/7 要求"中后肠分割掩码 + Dice≥0.85 + 仅掩码内计数"：
  只有肠内的细胞才计入炎症指标，肠外/前肠信号必须排除。
  本标注用于训练中后肠分割模型（U-Net 类），并作为评估真值。

{IMG_INFO}

【ROI 口径（依据需求文档，务必遵守）】
  本研究 ROI = 中肠 + 后肠（需求文档原文："本研究选取中肠与后肠区域作为
  感兴趣区（ROI）"，参照文档图1 红色轮廓）。
  ★ 前肠（含肠球部）明确排除在外——肠球部通常是画面中最亮的那团荧光，
    但它属于前肠，不在 ROI 内。把它画进来会导致计数系统性偏高
    （论文中 1279 个假阳性大半来自前肠/肠外信号，排除前肠正是
     本掩码的核心目的）。
  ★ 肠外（体壁、头部、尾部等肠道以外的荧光信号）一律不画。

【标注规范 —— 区域掩码】
  1. 每张图画 1 条闭合多边形轮廓（LabelMe 画完最后一点后"完成组"），
     圈住中肠+后肠。
  2. 前界：肠球部后缘、肠管明显变窄处（参照需求文档图1 轮廓起点）。
  3. 后界：肠道末端（近肛门处），后肠要完整画到末端，不要提前收尾。
  4. 边界沿肠道外壁的清晰解剖边界走；肠管内的荧光密集区必须完整包入。
  5. 边界不清时，取荧光信号明显衰减的位置为界。
  6. 不画多个区域、不加内部空洞，保持单条简单轮廓；轮廓平滑，
     不必跟着每个小抖动走。
  7. 口径一致比单张完美更重要：所有图用同一条前界规则，
     不要这张包肠球、下一张不包。
  8. 若图像中没有可辨识的中后肠（拍飞、糊片），在
     疑问记录.txt 中登记文件名，跳过该张。

【工具与输出】
  推荐 LabelMe 或 AnyLabeling（多边形分割）。
  方式A（推荐）：保存 LabelMe JSON 到本文件夹 masks_json/，
    文件名与图像同名（.json）。
  方式B：导出 PNG 二值掩码到 masks/（白=区域内，黑=区域外），
    与图像同名（.png）。
  两种方式都可以，请全文件夹统一用一种。

【关于本文件夹的图像】
  这里的图像是训练/测试文件夹中对应图像的拷贝（同一批图），
  因此掩码标注可与细胞框标注分批进行、由不同人完成。
  掩码只需画区域，不需要画细胞框。

【质控要求】
  每 10 张抽查 2 张：轮廓是否完整包住荧光密集区、
  有没有把前肠或肠外组织画进来。
  Dice 目标 ≥ 0.85，边界粗糙会直接拉低指标。

【本文件夹文件清单（共 {len(names)} 张，完成一项勾一项）】
{_checklist(names)}
"""


