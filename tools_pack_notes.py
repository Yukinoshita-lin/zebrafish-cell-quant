def write_all_notes(out_root: str, plan: Dict[str, List[dict]],
                    manifests: Dict[str, List[str]],
                    src_counts: Dict[str, int]) -> None:
    # 包内去重选中数（train+test，不含 mask 重复）
    sel: Dict[str, int] = {}
    for folder, its in plan.items():
        if folder.startswith("05"):
            continue
        for i in its:
            sel[i["stratum"]] = sel.get(i["stratum"], 0) + 1

    with open(os.path.join(out_root, "00_总览与进度.txt"), "w",
              encoding="utf-8") as f:
        f.write(note_overview({k: len(v) for k, v in plan.items()},
                              src_counts, sel))

    for folder, its in plan.items():
        names = manifests[folder]
        if folder.startswith("04"):
            text = note_test(names)
        elif folder.startswith("05"):
            text = note_mask(names)
        else:
            stratum = its[0]["stratum"] if its else ""
            text = note_train(stratum, folder, names,
                              EXTRA.get(folder, ""))
        with open(os.path.join(out_root, folder, "工作说明.txt"), "w",
                  encoding="utf-8") as f:
            f.write(text)
